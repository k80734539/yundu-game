const cache = new Map<string, HTMLCanvasElement>();
/** 把字串畫成圖（整數倍 scale） */
export function textImage(str: string, color: string, scale = 1, outline = '#1a1020'): HTMLCanvasElement {
  const k = str + '|' + color + '|' + scale + '|' + outline;
  let cv = cache.get(k);
  if (cv) return cv;
  const gw = 6, w = str.length * gw + 1, h = 9;
  const base = makeCanvas(w, h); const c = ctx2d(base);
  // 外框
  c.fillStyle = outline;
  for (let i = 0; i < str.length; i++) {
    const g = G[str[i]] || G[' '];
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (g[y][x] === '1') c.fillRect(i * gw + x, y, 3, 3);
  }
  c.fillStyle = color;
  for (let i = 0; i < str.length; i++) {
    const g = G[str[i]] || G[' '];
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (g[y][x] === '1') c.fillRect(i * gw + x + 1, y + 1, 1, 1);
  }
  cv = makeCanvas(w * scale, h * scale);
  const c2 = ctx2d(cv); c2.drawImage(base, 0, 0, w * scale, h * scale);
  if (cache.size > 600) cache.clear();
  cache.set(k, cv);
  return cv;
}
