"""Build the geometry guide and classic-script layout from the authored map data."""
import json, math, hashlib, copy
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'docs/maps/reeds-v43'
data=json.loads((OUT/'layout.json').read_text(encoding='utf-8-sig'))
rects=[]
for a,b in data['edges']:
    ax,ay=data['nodes'][a];bx,by=data['nodes'][b];r=data['pathWidth']/2
    rects.append([min(ax,bx)-r,min(ay,by)-r,abs(ax-bx)+2*r,abs(ay-by)+2*r])
data['walkRects']=rects
js="'use strict';\n// Generated by tools/build-reeds-map.py from docs/maps/reeds-v43/layout.json.\nconst REEDS_LAYOUT="+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n'
(ROOT/'src/reeds_layout.js').write_text(js,encoding='utf-8')
im=Image.new('RGB',(data['world']['width'],data['world']['height']),'#243c51');d=ImageDraw.Draw(im)
for a,b in data['edges']:
    points=[tuple(data['nodes'][a]),tuple(data['nodes'][b])];w=data['paintedPathWidth'];d.line(points,fill='#bca77c',width=w)
    for x,y in points:d.ellipse((x-w/2,y-w/2,x+w/2,y+w/2),fill='#bca77c')
for c in data['clearings']:d.ellipse((c['x']-c['rx']-12,c['y']-c['ry']-12,c['x']+c['rx']+12,c['y']+c['ry']+12),fill='#c8b58c')
for x,y,w,h in data['bridges']:d.rectangle((x,y,x+w,y+h),fill='#8d6548',outline='#edce9b',width=3)
for c in data['chests']:d.rectangle((c['x']-16,c['y']-12,c['x']+16,c['y']+12),fill='#ece09c');d.text((c['x']-24,c['y']+18),'CHEST SPACE',fill='white')
for name,point,col in [('ARRIVAL',data['nodes']['spawn'],'#83debe'),('STELE',data['stone']['base'],'#c9ddda'),('TALISMAN',(data['talisman']['x'],data['talisman']['y']),'#e8a4ed'),('CAMP STONES',(data['campfire']['x'],data['campfire']['y']),'#ffba74'),('EXIT',data['nodes']['exit'],'#d8cafe')]:
    x,y=point;d.ellipse((x-12,y-12,x+12,y+12),fill=col);d.text((x-38,y-28),name,fill='white')
d.text((990,300),'WRECK IN WATER',fill='white')
for g in data['gates']:d.text((g['x']-40,g['y']-8),'CLEAR BRIDGE',fill='#fff1cd')
im.save(OUT/'layout-guide.png')

def region(r):
    x,y,w,h=r
    return {'polygon':[[x,y],[x+w,y],[x+w,y+h],[x,y+h]]}
walk=[region(r) for r in rects]
for c in data['clearings']:
    walk.append({'polygon':[[round(c['x']+c['rx']*math.cos(i*math.tau/48),3),round(c['y']+c['ry']*math.sin(i*math.tau/48),3)] for i in range(48)]})
art=ROOT/'assets/img/reeds_map_v43.webp'
if art.exists():
    solids=[data['stone']['solid'],data['campfire']['solid']]+[[p['x']-16,p['y']-12,32,12] for p in data['chests']]
    base={'schema':'generate2dmap.map_bundle.v2','id':'reeds','name':'蘆葦蕩小迷宮',
          'world':{**data['world'],'unit':'px'},'art_source':'host_image',
          'layers':[{'name':'ground','kind':'image','image':'../../../assets/img/reeds_map_v43.webp','sha256':hashlib.sha256(art.read_bytes()).hexdigest()},{'name':'props','kind':'objects'}],
          'collision':{'actorRadius':8,'ySquash':1,'walkRegions':walk,'rects':solids},'nav':{'cell':4},
          'roads':[{'id':a+'-'+b,'material':'mud','width':data['pathWidth'],'polyline':[data['nodes'][a],data['nodes'][b]]} for a,b in data['edges']],
          'spawns':[{'id':'arrival','x':100,'y':122,'facing':'right'}],
          'interactions':[{'id':'stele','x':270,'y':128,'reach':38}],
          'camera':{'tiltDeg':35,'pixelToWorld':1,'bounds':[0,0,data['world']['width'],data['world']['height']]}}
    def obj(id,key,x,y,scale=1):
        p=ROOT/'assets/img'/key;w,h=Image.open(p).size
        return {'id':id,'prop':id,'image':'../../../assets/img/'+key,'image_sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'x':x,'y':y,'scale':scale,'anchor_px':[w/2,h],'sortY':y,'solid':False,'layer':'props'}
    for locked in [False,True]:
        b=copy.deepcopy(base);b['objects']=[]
        for i,p in enumerate(data['chests']):
            b['objects'].append(obj('chest-'+str(i),'chest.webp',p['x'],p['y']))
            if not locked or i<2:b['interactions'].append({'id':'chest-'+str(i),'x':p['x'],'y':p['y']+8,'reach':38})
        if locked:
            b['collision']['rects'] += [p['rect'] for p in data['gates']]
            b['objects'].append(obj('talisman','tal.webp',670,325,.8));b['interactions'].append({'id':'talisman','x':670,'y':338,'reach':20})
            for p in data['gates']:
                b['objects'].append(obj(p['id'],'reed_roots_v43.webp',p['x'],p['y']+21));b['interactions'].append({'id':p['id'],'x':p['x'],'y':p['y']-20,'reach':44})
        else:
            b['spawns'].append({'id':'camp','x':718,'y':590,'facing':'left'});b['interactions'].append({'id':'camp','x':718,'y':590,'reach':20})
            b['portals']=[{'id':'temple-exit','rect':data['exit']['zone'],'to':'temple','activation':'intent','travelDirection':[1,0],'radius':12,'reciprocal':False}]
        (OUT/('map-bundle-locked.json' if locked else 'map-bundle.json')).write_text(json.dumps(b,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print('Wrote guide, runtime layout and open/locked map bundles')
