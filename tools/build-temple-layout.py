"""把 docs/maps/temple-v52/layout-*.json 轉成 src/temple_layout.js（classic script，不用 build step 的遊戲直接載入）。
用法：python3 tools/build-temple-layout.py
改路線：改 JSON → 重跑 build-temple-guides.py（草圖）與本檔（遊戲資料）。"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'docs/maps/temple-v52'
out = {}
for key in ('shore', 'court', 'hall'):
    d = json.loads((SRC / f'layout-{key}.json').read_text(encoding='utf-8'))
    edges = []
    for e in d['edges']:
        opt = e[2] if len(e) > 2 else {}
        edges.append({'a': e[0], 'b': e[1], 'kind': opt.get('kind', 'path'), 'open': opt.get('open')})
    out[key] = {
        'id': d['id'], 'title': d['title'], 'world': d['world'], 'pathWidth': d['pathWidth'],
        'nodes': d['nodes'], 'edges': edges, 'clearings': d['clearings'],
        'overlays': d.get('overlays', []), 'zones': d.get('zones', {}),
        'features': {f['id']: f for f in d.get('features', [])},
        'encounters': d.get('encounters', []), 'upper': d.get('upper', []),
    }
js = ("'use strict';\n// Generated by tools/build-temple-layout.py from docs/maps/temple-v52/layout-*.json. 不要手改。\n"
      "const TEMPLE_LAYOUTS=" + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ";\n")
(ROOT / 'src/temple_layout.js').write_text(js, encoding='utf-8')
print('wrote src/temple_layout.js', len(js), 'bytes')
